    function copyText(text, okMsg) {
      var done = function (ok) {
        var el = $('export-status');
        if (el) {
          el.textContent = ok ? okMsg : 'Copy failed — use Download instead.';
          el.classList.toggle('error', !ok);
        }
      };
      if (navigator.clipboard && navigator.clipboard.writeText) {
        navigator.clipboard.writeText(text).then(function () { done(true); }, function () { done(false); });
      } else {
        var ta = document.createElement('textarea');
        ta.value = text;
        document.body.appendChild(ta);
        ta.select();
        try { done(document.execCommand('copy')); } catch (e) { done(false); }
        ta.remove();
      }
    }

    /* Canvas radar: current session polygon (lime) vs previous average (coral, dashed). */
    function drawRadar(canvas, data) {
      if (!canvas || !canvas.getContext) return;
      var ctx = canvas.getContext('2d');
      var W = canvas.width, H = canvas.height;
      var cx = W / 2, cy = H / 2 + 6, R = Math.min(W, H) / 2 - 46;
      var n = data.labels.length;
      ctx.clearRect(0, 0, W, H);
      var pt = function (i, v) {
        var a = -Math.PI / 2 + i * 2 * Math.PI / n;
        var r = R * Math.max(0, Math.min(10, v)) / 10;
        return [cx + r * Math.cos(a), cy + r * Math.sin(a)];
      };
      /* grid rings + spokes */
      ctx.strokeStyle = 'rgba(157,184,173,0.25)';
      ctx.lineWidth = 1;
      [2, 4, 6, 8, 10].forEach(function (v) {
        ctx.beginPath();
        for (var i = 0; i <= n; i++) {
          var p = pt(i % n, v);
          if (i === 0) ctx.moveTo(p[0], p[1]); else ctx.lineTo(p[0], p[1]);
        }
        ctx.stroke();
      });
      for (var s = 0; s < n; s++) {
        var sp = pt(s, 10);
        ctx.beginPath(); ctx.moveTo(cx, cy); ctx.lineTo(sp[0], sp[1]); ctx.stroke();
      }
      var poly = function (vals, stroke, fill, dashed) {
        var pts = [];
        for (var i = 0; i < n; i++) {
          if (vals[i] === null || vals[i] === undefined) return; // skip incomplete series
          pts.push(pt(i, vals[i]));
        }
        ctx.beginPath();
        pts.forEach(function (p, i) { if (i === 0) ctx.moveTo(p[0], p[1]); else ctx.lineTo(p[0], p[1]); });
        ctx.closePath();
        ctx.setLineDash(dashed ? [5, 4] : []);
        ctx.strokeStyle = stroke; ctx.lineWidth = 2; ctx.stroke();
        ctx.setLineDash([]);
        ctx.fillStyle = fill; ctx.fill();
      };
      poly(data.previous, '#fb7185', 'rgba(251,113,133,0.08)', true);
      poly(data.current, '#a3e635', 'rgba(163,230,53,0.10)', false);
      /* labels */
      ctx.fillStyle = '#9db8ad';
      ctx.font = '11px system-ui, sans-serif';
      ctx.textAlign = 'center';
      data.labels.forEach(function (l, i) {
        var a = -Math.PI / 2 + i * 2 * Math.PI / n;
        var lx = cx + (R + 30) * Math.cos(a), ly = cy + (R + 30) * Math.sin(a);
        var short = l.label.replace('ML ', '');
        ctx.fillText(short, lx, ly);
      });
      /* legend */
      ctx.textAlign = 'left';
      ctx.fillStyle = '#a3e635'; ctx.fillText('— this session', 12, H - 24);
      ctx.fillStyle = '#fb7185'; ctx.fillText('- - previous avg', 12, H - 10);
    }

