  function signalFor(overall) {
    if (overall >= 8) return { label: 'Strong hire signal', cls: 'sig-strong' };
    if (overall >= 6.5) return { label: 'Hire signal', cls: 'sig-hire' };
    if (overall >= 5) return { label: 'Mixed \u2014 keep practicing', cls: 'sig-mixed' };
    return { label: 'Needs work', cls: 'sig-weak' };
  }

  /* scored: [{ question:{id,category,q}, result:{score,dimensions,feedback,words} }] */
  function generateDrills(scored) {
    var drills = [];
    var noResult = 0, short = 0, fillerHeavy = 0, weakTerm = {};
    scored.forEach(function (s) {
      var r = s.result, d = r.dimensions;
      if (s.question.category === 'behavioral' && d.structure < 7.5) noResult++;
      if (r.words < 120) short++;
      if (d.clarity < 7) fillerHeavy++;
      if (d.terminology < 6) weakTerm[s.question.category] = (weakTerm[s.question.category] || 0) + 1;
    });
    if (noResult >= 2) drills.push('STAR closings: ' + noResult + ' behavioral answers missed beats (often the Result). For each story, write the last two sentences first — the quantified outcome — then tell the rest.');
    if (short >= 2) drills.push('Depth: ' + short + ' answers ran under 120 words. Pick one and expand it with a concrete example, a number, and a tradeoff you considered.');
    if (fillerHeavy >= 2) drills.push('Delivery: ' + fillerHeavy + ' answers were filler-heavy. Re-answer one out loud, pausing instead of saying "um" / "basically".');
    var worstCat = Object.keys(weakTerm).sort(function (a, b) { return weakTerm[b] - weakTerm[a]; })[0];
    if (worstCat && weakTerm[worstCat] >= 2) {
      var label = catLabel(worstCat);
      drills.push(label + ' vocabulary: ' + weakTerm[worstCat] + ' answers missed expected terms. Make flashcards of the "looks for" hints in your report and re-answer one question using them.');
    }
    if (!drills.length) drills.push('Solid round. Next drill: re-answer your lowest-scored question with a 2-minute timer — pressure is the remaining gap.');
    return drills.slice(0, 3);
  }

  function catLabel(id) {
    var map = { mixed: 'Mixed', behavioral: 'Behavioral', 'ml-fundamentals': 'ML fundamentals', 'ml-system-design': 'ML system design', 'resume-deep-dive': 'Resume deep-dive', 'evals-guardrails': 'Evals & guardrails' };
    return map[id] || id;
  }

  /* ---------- markdown export (pure) ---------- */

  function buildMarkdownReport(report, meta) {
    meta = meta || {};
    var L = [];
    L.push('# PrepAgent report card');
    L.push('');
    L.push('- Date: ' + (meta.date || new Date().toISOString()));
    if (meta.company) L.push('- Company: ' + meta.company);
    L.push('- Round type: ' + catLabel(meta.roundType || 'mixed'));
    L.push('- Overall: **' + report.overall + '/10** — ' + report.signal.label);
    L.push('');
    L.push('## Per-question scores');
    L.push('');
    report.perQuestion.forEach(function (p, i) {
      L.push((i + 1) + '. **' + p.score + '/10** [' + catLabel(p.category) + '] ' + p.q);
      (p.feedback || []).forEach(function (f) { L.push('   - ' + f); });
    });
    L.push('');
    L.push('## Weak areas');
    L.push('');
    report.weakAreas.forEach(function (w) {
      L.push('- ' + catLabel(w.category) + ': ' + w.avg + '/10');
    });
    L.push('');
    L.push('## Drills');
    L.push('');
    report.drills.forEach(function (d, i) { L.push((i + 1) + '. ' + d); });
    L.push('');
    L.push('_Generated by PrepAgent — 100% client-side._');
    return L.join('\n');
  }

  /* ---------- radar data (pure) ---------- */

  /* Shapes per-category averages for the radar chart, aligned to CATEGORIES
   * order: { labels: [{id,label}], current: [v|null], previous: [v|null] }.
   * current = latest session; previous = mean of up to 4 sessions before it. */
  function buildRadarData(sessions) {
    var cats = root.PrepAgent.Questions.CATEGORIES;
    var avgFor = function (list, catId) {
      var sum = 0, n = 0;
      list.forEach(function (s) {
        (s.questions || []).forEach(function (q) {
          if (q.category === catId && typeof q.score === 'number') { sum += q.score; n++; }
        });
      });
      return n ? Math.round(sum / n * 10) / 10 : null;
    };
    var labels = cats.map(function (c) { return { id: c.id, label: c.label }; });
    var current = labels.map(function (l) { return sessions.length ? avgFor(sessions.slice(0, 1), l.id) : null; });
    var previous = labels.map(function (l) { return sessions.length > 1 ? avgFor(sessions.slice(1, 5), l.id) : null; });
    return { labels: labels, current: current, previous: previous };
  }

  function buildReport(scored) {
    var perQuestion = scored.map(function (s) {
      return {
        id: s.question.id, category: s.question.category, q: s.question.q,
        score: s.result.score, dimensions: s.result.dimensions,
        feedback: s.result.feedback, words: s.result.words,
        followupsUsed: s.followupsUsed || 0
      };
    });
    var overall = perQuestion.length
      ? Math.round(perQuestion.reduce(function (a, p) { return a + p.score; }, 0) / perQuestion.length * 10) / 10
      : 0;
    var byCat = {}, byCatN = {};
    perQuestion.forEach(function (p) {
      byCat[p.category] = (byCat[p.category] || 0) + p.score;
      byCatN[p.category] = (byCatN[p.category] || 0) + 1;
    });
    var weakAreas = Object.keys(byCat).map(function (c) {
      return { category: c, avg: Math.round(byCat[c] / byCatN[c] * 10) / 10 };
    }).sort(function (a, b) { return a.avg - b.avg; }).slice(0, 3);
    return {
      perQuestion: perQuestion,
      overall: overall,
      signal: signalFor(overall),
      weakAreas: weakAreas,
      drills: generateDrills(scored)
    };
  }

